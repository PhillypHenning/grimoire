-- Wraps a Prophecy plan file in Lua so Homunculus_Prophecy ships it (ADR 0006's
-- fallback: plans too large to paste). The plan is checked first; a plan with errors
-- isn't bundled.
--   lua scripts/prophecy/bundle.lua <plan.prophecy> <Homunculus_Prophecy/Plans/name.lua>
-- Add a new output file to Homunculus_Prophecy.toc, then restart the game.

local here = arg[0]:match("^(.*)[/\\]") or "."
local Parser = dofile(here .. "/../../Homunculus_Prophecy/Parser.lua")

local input, output = arg[1], arg[2]
if not (input and output) then
	io.stderr:write("usage: lua bundle.lua <plan.prophecy> <output.lua>\n")
	os.exit(2)
end
local file = assert(io.open(input, "rb"))
local text = file:read("*a"):gsub("^\239\187\191", ""):gsub("\r\n", "\n")
file:close()

local plan, errors = Parser.Parse(text)
if not plan then
	for _, e in ipairs(errors) do
		print(("%s:%d: error: %s"):format(input, e.line, e.message))
	end
	os.exit(1)
end

-- The shortest long-bracket level whose closing bracket isn't in the text.
local level = ""
while text:find("]" .. level .. "]", 1, true) do
	level = level .. "="
end

local name = input:gsub("\\", "/"):match("([^/]+)$")
file = assert(io.open(output, "wb"))
file:write(("-- Generated by scripts/prophecy/bundle.lua from %s. Edit that file and re-run\n"):format(name))
file:write("-- the script instead of changing this one.\n")
file:write("local _, ns = ...\n")
file:write(("ns.bundledPlans[#ns.bundledPlans + 1] = [%s[\n%s]%s]\n"):format(level, text, level))
file:close()
print(("Bundled \"%s\" into %s"):format(plan.title, output))
